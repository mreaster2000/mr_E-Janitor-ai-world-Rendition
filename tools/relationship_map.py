#!/usr/bin/env python3
"""Generate RELATIONSHIPS.md: who is connected to whom, from BIO section 7 bullets."""
import glob,json,os,re
root=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M=json.load(open(root+'/characters/manifest.json'))['characters']
def disp(s):
    t=open(f'{root}/characters/{M[s]}/CARD.md').read()
    m=re.search(r'^# (.+?) — Unified Card',t,re.M);return m[1] if m else s
names={s:disp(s) for s in M}
tok={}
for s,n in names.items():
    keys={n.lower()}
    first=n.split()[0].lower().strip('()')
    if len(first)>3:keys.add(first)
    keys.add(s.replace('-',' '))
    tok[s]=keys
edges={s:set() for s in M}
for s,d in M.items():
    t=open(f'{root}/characters/{d}/BIO.md').read()
    m=re.search(r'## 7\. [^\n]*\n(.*?)\n## 8\.',t,re.S)
    if not m:continue
    for line in m[1].splitlines():
        b=re.match(r'- \*\*(.+?):?\*\*',line)
        if not b:continue
        head=b[1].lower()
        if head in ('family','friends/allies','social circles','rivals/enemies','allies','rivals'): head=head+' '+line.lower()
        for o,keys in tok.items():
            if o!=s and any(re.search(r'\b'+re.escape(k)+r'\b',head) for k in keys):edges[s].add(o)
for s in list(edges):
    for o in list(edges[s]):edges[o].add(s)
out=["# Relationship map","","Generated by `python3 tools/relationship_map.py` from each BIO's section 7. Links are symmetric; being listed here never means a character appears in a scene.","","| Character | Connected to |","|---|---|"]
for s in sorted(M,key=lambda x:names[x].lower()):
    links=', '.join(f"[{names[o]}](characters/{M[o]}/)" for o in sorted(edges[s],key=lambda x:names[x].lower())) or '—'
    out.append(f"| [{names[s]}](characters/{M[s]}/) | {links} |")
out+=["",f"Total connections: {sum(len(v) for v in edges.values())//2}.",""]
open(root+'/RELATIONSHIPS.md','w').write('\n'.join(out))
print('edges',sum(len(v) for v in edges.values())//2)
